# ════════════════════════════════════════════════════════════════════════
# 0. Что такое HTTP: протокол, клиент-сервер, анатомия запроса/ответа
# ════════════════════════════════════════════════════════════════════════
# HTTP (HyperText Transfer Protocol) — это ПРОТОКОЛ: заранее согласованный
# ФОРМАТ общения между двумя программами по сети. "Протокол" здесь то же
# слово, что в дипломатии — жёсткий регламент "кто, что и в каком порядке
# говорит", только для программ, а не для людей.
#
# Зачем это вообще нужно: браузер Chrome, curl в терминале, мобильное
# приложение на Java и твой Python-сервер ниже — всё это написано разными
# людьми на разных языках, они ничего не знают о внутреннем устройстве
# друг друга. Но если все они умеют читать и писать ОДИН и тот же формат
# HTTP-запроса/ответа — они могут общаться. Это ровно та же идея, что
# JSON как общий формат данных (блок 2.4): не важно, кто и на чём это
# сгенерировал, если формат общий — любой другой умеет его прочитать.
#
# Модель — "клиент-сервер":
#   КЛИЕНТ (браузер / curl / функция request() в разделе 5 этого файла)
#     — ВСЕГДА первым открывает разговор.
#   СЕРВЕР (класс ItemsHandler ниже) — ВСЕГДА слушает и отвечает; сам
#     разговор не начинает и не может "написать" клиенту без вопроса.
#
# Что происходит физически, шаг за шагом:
#   1. Клиент открывает TCP-соединение к серверу (адрес + порт). TCP —
#      отдельный, более низкоуровневый протокол: он гарантирует, что
#      байты дойдут в правильном порядке и без потерь. HTTP работает
#      "поверх" TCP и не заботится о доставке байт — это забота уровня
#      ниже.
#   2. Клиент отправляет запрос — обычный ТЕКСТ по строгому формату
#      (см. пример ниже).
#   3. Сервер читает этот текст, обрабатывает (в нашем случае — код
#      в do_GET/do_POST/... из раздела 5) и отправляет обратно
#      текстовый ответ, тоже по строгому формату.
#   4. Один запрос — РОВНО один ответ. Соединение затем закрывается
#      (или переиспользуется для следующего запроса — детали сейчас
#      не важны).
#
# КАК ВЫГЛЯДИТ ЭТОТ ТЕКСТ НА САМОМ ДЕЛЕ (то, что реально едет по сети,
# байт в байт, когда сервер из раздела 5 обработает
# `POST /items {"title": "Buy milk"}`):
#
#     ЗАПРОС (клиент -> сервер):
#     ┌────────────────────────────────────────────────
#     │ POST /items HTTP/1.1                              <- start line
#     │ Host: localhost:54321                              <- заголовок
#     │ Content-Type: application/json                     <- заголовок
#     │ Content-Length: 21                                 <- заголовок
#     │                                                     <- ПУСТАЯ строка
#     │ {"title": "Buy milk"}                               <- тело
#     └────────────────────────────────────────────────
#
#     ОТВЕТ (сервер -> клиент):
#     ┌────────────────────────────────────────────────
#     │ HTTP/1.1 201 Created                               <- start line
#     │ Content-Type: application/json                     <- заголовок
#     │ Location: /items/1                                 <- заголовок
#     │ Content-Length: 21                                 <- заголовок
#     │                                                     <- ПУСТАЯ строка
#     │ {"title": "Buy milk"}                               <- тело
#     └────────────────────────────────────────────────
#
# Три части, всегда в этом порядке: (1) start line — у запроса это
# "метод + путь + версия протокола", у ответа "версия + код + причина";
# (2) заголовки — по одному на строку, "Имя: значение"; (3) после
# ОБЯЗАТЕЛЬНОЙ пустой строки — тело (может отсутствовать).
#
# Когда в коде раздела 5 ты видишь `self.path`, `self.headers`,
# `self.rfile` — это уже РАСПАРСЕННЫЕ части ровно этого текста;
# BaseHTTPRequestHandler сделал разбор текста в атрибуты объекта за
# тебя. А `conn.request(...)` / `resp.status` / `resp.read()` в разделе
# 5, наоборот, СОБИРАЮТ этот текст из аргументов Python и разбирают
# текст ответа обратно в Python-объекты.
#
# Дополнительный мост к тому, что ты уже писал: HTTP-запрос очень похож
# на вызов функции, просто через сеть, а не в памяти одного процесса:
#
#     функция                        HTTP-запрос
#     ────────────────────────────   ────────────────────────────────
#     имя функции                    метод + путь (POST /items)
#     аргументы                      заголовки + тело запроса
#     return значение                статус-код + тело ответа
#     raise ValueError(...)          статус-код 4xx/5xx + тело с ошибкой
#
# С одной разницей: вызов функции никогда "не долетает" — а сетевой
# запрос физически может не дойти (сеть упала), поэтому у HTTP есть
# отдельная категория кодов именно для "запрос не дошёл или сервер
# сломался" (5xx), в отличие от "дошёл, но данные неправильные" (4xx) —
# см. раздел 2.


# ════════════════════════════════════════════════════════════════════════
# 1. Методы: GET/POST/PUT/PATCH/DELETE — семантика и зачем их несколько
# ════════════════════════════════════════════════════════════════════════
# Из анатомии выше: start line запроса — это "метод + путь". Путь
# ("/items/1") описывает КАКАЯ сущность, а метод — ЧТО С НЕЙ СДЕЛАТЬ.
# Один и тот же путь ведёт себя по-разному в зависимости именно от
# метода.
#
# Зачем нужно СОГЛАСОВАННОЕ разделение на 5 методов, а не один метод
# "сделай что-нибудь" с описанием действия в теле: по методу без чтения
# тела уже понятно, БЕЗОПАСНО ЛИ повторить запрос при сбое связи.
# Браузер, прокси, балансировщик нагрузки — никто из них не знает
# домен "книги" или "тикеты", но все они умеют посмотреть на метод и
# понять: GET/PUT/DELETE можно спокойно повторить, если ответ не
# дошёл (результат от повтора не изменится — это называется
# идемпотентность), а POST повторять нельзя не глядя — можно создать
# вторую сущность.
#
# GET     — прочитать данные, ничего не меняя (аналог обращения к
#           словарю по ключу: `items[1]`, без побочных эффектов).
#           Идемпотентен: повторить 100 раз — ничего не изменится.
# POST    — создать новую сущность (аналог `items.append(x)` — каждый
#           вызов добавляет ЕЩЁ ОДНУ запись, даже с теми же данными).
#           НЕ идемпотентен: повторный вызов создаст дубликат.
# PUT     — заменить сущность ЦЕЛИКОМ (аналог `items[1] = new_item` —
#           старые поля, которых нет в новом объекте, теряются).
#           Идемпотентен: повторный вызов с теми же данными даст тот
#           же результат.
# PATCH   — обновить сущность ЧАСТИЧНО (аналог `items[1].update(...)`
#           или смены одного поля dataclass — остальные поля не трогает).
# DELETE  — удалить сущность (аналог `del items[1]`).
#           Идемпотентен: удалить уже удалённое — тот же итог ("нет").


# ════════════════════════════════════════════════════════════════════════
# 2. Статус-коды: категории 1xx-5xx и зачем они вообще нужны
# ════════════════════════════════════════════════════════════════════════
# Из анатомии выше: start line ответа несёт код + текстовую причину
# ("201 Created"). Зачем нужен именно ЧИСЛОВОЙ код, а не только текст:
# число можно проверить программно ОДНОЙ строкой (`if status < 300`),
# не разбирая текст на человеческом языке, и любая HTTP-библиотека на
# любом языке заранее знает стандартные диапазоны — например, коды
# 3xx браузер САМ автоматически обработает как редирект, даже не
# показав тебе содержимое ответа.
#
# 1xx — информационные (встречаются редко, пропускаем)
# 2xx — успех:
#       200 OK              — успех, есть тело ответа (GET/PUT/PATCH)
#       201 Created         — успех, создана новая сущность (POST)
#       204 No Content      — успех, тела ответа НЕТ (DELETE)
# 3xx — редирект (например 301 — ресурс переехал на другой URL)
# 4xx — ошибка НА СТОРОНЕ КЛИЕНТА (запрос дошёл, но он неправильный):
#       400 Bad Request     — некорректные данные в теле запроса
#       404 Not Found       — такой сущности/пути не существует
#       422 Unprocessable   — данные не прошли валидацию (Pydantic,
#                             тема 4, будет отдавать именно этот код)
# 5xx — ошибка НА СТОРОНЕ СЕРВЕРА (сервер сломался при обработке):
#       500 Internal Server Error — необработанное исключение в коде
#
# Параллель с исключениями (блок 2.7): 4xx ~ ValueError (клиент передал
# то, чего не должен был), 5xx ~ необработанный баг в самом сервере.


# ════════════════════════════════════════════════════════════════════════
# 3. Заголовки: зачем метаданные едут отдельно от тела
# ════════════════════════════════════════════════════════════════════════
# Из анатомии выше: между start line и телом — блок заголовков,
# "Имя: значение" построчно, как dict. Зачем это ОТДЕЛЬНЫЙ блок, а не
# просто часть тела: тело может быть ЧЕМ УГОДНО — JSON, HTML-страница,
# картинка в байтах — и сервер/прокси/браузер по пути должны понять
# несколько вещей ПРО тело, ДО того как начнут его читать и
# разбирать: в каком оно формате (Content-Type), сколько в нём байт
# (Content-Length, чтобы понять, где тело заканчивается), и так далее.
# Заголовки — это метаданные "об упаковке", тело — само содержимое;
# их разделяют, чтобы не парсить полностью произвольное тело только
# ради этих служебных фактов.
#
# В запросе (клиент → сервер), например:
#   Content-Type: application/json   — "тело запроса в формате JSON"
#   Authorization: Bearer <token>    — "вот кто я" (тема 2.9.5, DI)
#
# В ответе (сервер → клиент), например:
#   Content-Type: application/json   — "тело ответа в формате JSON"
#   Content-Length: 42               — размер тела в байтах
#   Location: /items/1               — где искать только что созданную
#                                       сущность (обычно вместе с 201)


# ════════════════════════════════════════════════════════════════════════
# 4. Тело запроса/ответа: JSON и зачем нужен Content-Type
# ════════════════════════════════════════════════════════════════════════
# Тело в анатомии из раздела 0 — это часть текста ПОСЛЕ пустой строки.
# Само по себе HTTP тело — это просто последовательность байт, протокол
# НЕ ЗНАЕТ и не диктует, что там внутри: HTML-страница, картинка,
# CSV-файл, JSON — что угодно. Именно поэтому заголовок Content-Type
# (раздел 3) обязателен для непустого тела: он говорит принимающей
# стороне, КАК интерпретировать эти байты. Мы всегда используем
# `application/json`, потому что для API это стандарт — оба конца
# (сервер и клиент) заранее согласились обмениваться JSON.
#
# json.dumps()/json.loads() ты уже использовал в блоке 2.4
# (16_io_and_files). Здесь та же пара функций, просто тело едет не в
# файл, а по сети: json.dumps(dict) → bytes → в тело запроса/ответа,
# и обратно json.loads(bytes) на другом конце.


# ════════════════════════════════════════════════════════════════════════
# 5. Всё вместе: мини CRUD-сервис "items" + реальные запросы
# ════════════════════════════════════════════════════════════════════════
# "База данных" — обычный словарь в памяти процесса (никакого
# SQLAlchemy — это чистый протокол, БД подключим в теме 6).
#
# Как это работает "под капотом" (stdlib-магия, на которой стоит
# HTTPServer): ты даёшь HTTPServer класс-наследник BaseHTTPRequestHandler.
# На КАЖДЫЙ входящий запрос сервер сам создаёт экземпляр этого класса и
# сам вызывает метод с именем do_<HTTP-МЕТОД> — do_GET, do_POST и т.д.
# Диспетчеризация "какой метод дернуть" уже сделана базовым классом по
# имени HTTP-метода запроса — поэтому здесь нет ручного
# `if method == "GET": ...`.
#
# Внутри каждого do_* метода `self` — это как раз этот экземпляр-на-один-
# запрос, и у него уже готовы (заполнены базовым классом ДО вызова do_*):
#   self.path    — путь запроса, например "/items/1"
#   self.headers — заголовки запроса
#   self.rfile   — поток ЧТЕНИЯ тела запроса (как открытый файл)
#   self.wfile   — поток ЗАПИСИ тела ответа (как открытый файл)

items: dict[int, dict[str, str]] = {}
next_id = 1


class ItemsHandler(BaseHTTPRequestHandler):
    """Обработчик HTTP-запросов для пути /items и /items/<id>."""

    # Три приватных метода ниже (префикс "_" = внутреннее, не часть
    # API do_*) — вынесенное наружу дублирование, которое иначе
    # повторялось бы в каждом do_GET/do_POST/... по отдельности.

    def _send_json(self, status: int, payload: object | None) -> None:
        # None (напр. для 204) -> пустые байты; иначе dict -> JSON-текст -> bytes,
        # т.к. по сети едут именно байты, а не Python-объекты.
        body = b"" if payload is None else json.dumps(payload).encode("utf-8")
        # Пишет start line ответа: "HTTP/1.1 <status> <причина>" (раздел 0).
        self.send_response(status)
        # Заголовок: говорит клиенту, как интерпретировать байты тела (раздел 4).
        self.send_header("Content-Type", "application/json")
        # Заголовок: сколько байт тела ждать, чтобы клиент понял, где оно кончится.
        self.send_header("Content-Length", str(len(body)))
        # Пишет обязательную пустую строку-разделитель между заголовками и телом.
        self.end_headers()
        if body:
            # Само тело пишем отдельно и только если оно не пустое (204 без тела).
            self.wfile.write(body)

    def _read_json_body(self) -> dict[str, str]:
        # Без длины неизвестно, сколько байт тела читать из потока (тело не
        # заканчивается спецсимволом, границу задаёт именно этот заголовок).
        length = int(self.headers.get("Content-Length", 0))
        # Читаем ровно `length` байт тела запроса из rfile (см. раздел 0).
        raw = self.rfile.read(length)
        # bytes -> Python dict, обратная операция к json.dumps в _send_json.
        return json.loads(raw)

    def _parse_item_id(self) -> int | None:
        # "/items/1" -> ["items", "1"]; strip("/") убирает крайние слэши,
        # чтобы split не дал пустую строку первым элементом.
        parts = self.path.strip("/").split("/")
        if len(parts) != 2:
            # Путь не формата "/items/<id>" — например просто "/items" или "/nope".
            return None
        try:
            # Пробуем превратить текст после "/" в число — это и есть id.
            return int(parts[1])
        except ValueError:
            # После "/items/" стоит не число (например "/items/abc") — невалидно.
            return None

    # do_GET вызывается сервером САМ, когда пришёл GET-запрос — см.
    # объяснение диспетчеризации по do_<МЕТОД> в комментарии над классом.
    def do_GET(self) -> None:
        if self.path == "/items":
            # Клиент попросил всю коллекцию целиком — отдаём словарь как есть.
            self._send_json(200, items)
            return
        # Иначе пробуем достать id из пути вида "/items/<id>".
        item_id = self._parse_item_id()
        if item_id is not None and item_id in items:
            # id распарсился И такая запись есть — отдаём именно её.
            self._send_json(200, items[item_id])
            return
        # Либо id не распарсился, либо записи с таким id нет — оба случая 404.
        self._send_json(404, {"detail": "Not Found"})

    # Ответ собран вручную (send_response/send_header/end_headers/
    # wfile.write), а не через _send_json — потому что нужен ДОПОЛНИТЕЛЬНЫЙ
    # заголовок Location, которого у _send_json нет.
    def do_POST(self) -> None:
        # next_id объявлена вне класса (уровень модуля); без global строка
        # "next_id += 1" ниже создала бы НОВУЮ локальную переменную вместо
        # изменения глобальной (LEGB, блок 2.3).
        global next_id
        if self.path != "/items":
            # POST разрешён только на саму коллекцию, не на "/items/<id>".
            self._send_json(404, {"detail": "Not Found"})
            return
        # Тело запроса (JSON) -> Python dict с данными новой сущности.
        data = self._read_json_body()
        # Сохраняем под следующим свободным id — вот что значит "создать".
        items[next_id] = data
        # start line ответа: "HTTP/1.1 201 Created".
        self.send_response(201)
        self.send_header("Content-Type", "application/json")
        # ДОПОЛНИТЕЛЬНЫЙ заголовок (см. коммент над методом) — где теперь
        # искать созданную сущность по её новому адресу.
        self.send_header("Location", f"/items/{next_id}")
        # Тело ответа — то же самое, что только что сохранили.
        body = json.dumps(data).encode("utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
        # Готовим id для СЛЕДУЮЩЕГО POST — иначе вторая книга затрёт первую.
        next_id += 1

    def do_PUT(self) -> None:
        item_id = self._parse_item_id()
        if item_id is None or item_id not in items:
            # Нельзя заменить то, чего нет.
            self._send_json(404, {"detail": "Not Found"})
            return
        # ПОЛНАЯ замена: старое значение по ключу отбрасывается целиком,
        # поля, которых нет в новом теле, теряются (см. раздел 1).
        items[item_id] = self._read_json_body()
        # Отдаём итоговое состояние сущности после замены.
        self._send_json(200, items[item_id])

    def do_PATCH(self) -> None:
        item_id = self._parse_item_id()
        if item_id is None or item_id not in items:
            # Нельзя обновить то, чего нет.
            self._send_json(404, {"detail": "Not Found"})
            return
        # ЧАСТИЧНОЕ обновление: dict.update() трогает только переданные
        # ключи, остальные поля сущности остаются как были (см. раздел 1).
        items[item_id].update(self._read_json_body())
        self._send_json(200, items[item_id])

    def do_DELETE(self) -> None:
        item_id = self._parse_item_id()
        if item_id is None or item_id not in items:
            # Нельзя удалить то, чего нет.
            self._send_json(404, {"detail": "Not Found"})
            return
        # Удаляем запись из словаря — необратимо, в отличие от PUT/PATCH.
        del items[item_id]
        # 204: успех, но тела намеренно нет — про удалённую сущность
        # возвращать нечего (см. раздел 2, категория 2xx).
        self._send_json(204, None)

    def log_message(self, format: str, *args: object) -> None:
        pass  # отключаем стандартный лог сервера, чтобы не мешал выводу демо


def request(method: str, path: str, port: int, body: dict[str, str] | None = None) -> None:
    """Отправить реальный HTTP-запрос к локальному серверу и напечатать ответ."""
    conn = http.client.HTTPConnection("localhost", port)
    headers = {"Content-Type": "application/json"} if body is not None else {}
    data = json.dumps(body).encode("utf-8") if body is not None else None
    conn.request(method, path, body=data, headers=headers)
    resp = conn.getresponse()
    raw = resp.read()
    parsed = json.loads(raw) if raw else None
    print(f"{method} {path} -> {resp.status} {resp.reason}")
    print(f"  Content-Type: {resp.getheader('Content-Type')}", end="")
    location = resp.getheader("Location")
    if location:
        print(f", Location: {location}", end="")
    print()
    print(f"  body: {parsed}")
    conn.close()


