# ════════════════════════════════════════════════════════════════════════
# 1. Напоминание: статический чекер vs рантайм
# ════════════════════════════════════════════════════════════════════════
# Аннотации типов (`x: int`) сами по себе НИЧЕГО не проверяют во время
# выполнения — Python их полностью игнорирует при запуске (см. Блок
# 2.6, тема 1). Проверку выполняет ОТДЕЛЬНАЯ программа — статический
# чекер, — которая читает код, но не запускает его, и ищет
# несоответствия между объявленными типами и тем, как эти значения
# реально используются. mypy и pyright — два самых распространённых
# таких чекера для Python.


# ════════════════════════════════════════════════════════════════════════
# 2. mypy vs pyright — в чём разница
# ════════════════════════════════════════════════════════════════════════
#                    mypy                        pyright
#   Кто делает       эталонная реализация от      Microsoft, тот же
#                     Python core-разработчиков     движок, что и в
#                                                    Pylance (VS Code)
#   На чём написан    Python                        TypeScript
#   Скорость          медленнее на больших          заметно быстрее
#                      проектах
#   Экосистема        много плагинов (Django,       меньше плагинов,
#                      SQLAlchemy и т.д.)             но отличная
#                                                      поддержка в VS Code
#   strict из коробки  нужно явно включать флаги      есть готовый режим
#                       по одному                      "strict" целиком
#
# На практике многие проекты используют ОБА (mypy — в CI как эталон,
# pyright/Pylance — в редакторе для мгновенной обратной связи) или
# только один. В этом репозитории с сеанса 10 уже используется pyright
# (через `npx pyright`) — сейчас разберём, ПОЧЕМУ он настроен именно
# так, и попробуем mypy рядом для сравнения.


# ════════════════════════════════════════════════════════════════════════
# 3. Установка и запуск
# ════════════════════════════════════════════════════════════════════════
# pyright — пакет из мира Node.js, поэтому в этом репо он запускается
# через `npx` (скачивает и кэширует пакет на лету, установка Node.js
# нужна один раз):
#
#     npx pyright                     # проверить весь проект
#     npx pyright путь/к/файлу.py     # проверить один файл
#
# mypy — обычный Python-пакет, ставится через pip:
#
#     pip install mypy
#     mypy путь/к/файлу.py            # проверить один файл
#     mypy .                          # проверить весь проект
#
# Оба инструмента можно запускать без установки в проект — они не
# меняют ничего в самом коде, только читают файлы и печатают отчёт.


# ════════════════════════════════════════════════════════════════════════
# 4. Файлы конфигурации
# ════════════════════════════════════════════════════════════════════════
# Без файла конфигурации оба чекера используют настройки по умолчанию,
# которые слабее, чем хотелось бы для обучения. Конфиг кладётся в
# КОРЕНЬ репозитория и подхватывается автоматически.
#
#   для pyright:  pyrightconfig.json  ИЛИ  [tool.pyright] в pyproject.toml
#   для mypy:     mypy.ini  ИЛИ  setup.cfg [mypy]  ИЛИ  [tool.mypy] в
#                 pyproject.toml
#
# В этом репозитории уже есть `pyrightconfig.json` в корне:
#
#     {
#       "typeCheckingMode": "strict",
#       "pythonVersion": "3.12"
#     }
#
#   - "typeCheckingMode": "strict" — включает ВСЕ проверки pyright
#     (а не только базовые)
#   - "pythonVersion": "3.12" — чекер учитывает, какой синтаксис и
#     какая стандартная библиотека доступны в этой версии Python


# ════════════════════════════════════════════════════════════════════════
# 5. basic vs strict — реальная ловушка этого репозитория
# ════════════════════════════════════════════════════════════════════════
# До сеанса 10 (2026-07-06) в репозитории НЕ было pyrightconfig.json.
# Результат: команда `npx pyright файл.py` молча проверяла файл в
# режиме "basic" — слабом, который пропускает много реальных проблем
# (отсутствие аннотаций, Any там, где не должно быть, и т.д.) — и
# честно печатала "0 errors", хотя по факту строгая проверка нашла бы
# ошибки. Это не было видно, пока не сравнили с настройками strict в
# самом VS Code (Pylance).
#
# Вывод: наличие `pyrightconfig.json` со `"typeCheckingMode": "strict"`
# в КОРНЕ репозитория — не опция, а обязательное условие, чтобы
# `npx pyright` вообще проверял в том режиме, который нужен. То же
# самое верно для mypy: без явного `strict = true` в конфиге он тоже
# проверяет мягче, чем можно ожидать.


# ════════════════════════════════════════════════════════════════════════
# 6. Как читать вывод чекера
# ════════════════════════════════════════════════════════════════════════
# Формат строки ошибки у pyright:
#
#   путь/к/файлу.py:28:12 - error: Type "int" is not assignable to
#   declared type "str" (reportAssignmentType)
#
#   28   — номер строки
#   12   — номер колонки (символа в строке)
#   error: ...  — сообщение
#   (reportAssignmentType) — КОД правила; именно его используют,
#                             чтобы подавить ОДНУ конкретную проверку,
#                             а не все сразу
#
# У mypy формат похожий, но код правила пишется в квадратных скобках
# в конце сообщения:
#
#   путь/к/файлу.py:28: error: Incompatible types in assignment
#   (expression has type "int", variable has type "str")  [assignment]


# ════════════════════════════════════════════════════════════════════════
# 7. Подавление ошибок: # type: ignore vs # pyright: ignore
# ════════════════════════════════════════════════════════════════════════
# Иногда ошибка — не баг, а сознательная демонстрация (уже встречалось
# в блоках 2.5–2.6: намеренный вызов абстрактного класса, литерал для
# примера и т.д.). Тогда её подавляют комментарием НА ТОЙ ЖЕ строке:


def broken_on_purpose() -> int:
    """Демонстрация: намеренно неверный возврат, чтобы показать
    подавление ошибки."""
    return "not an int"  # type: ignore[return-value]
    # ^ `# type: ignore[код]` — стандарт PEP 484, понимают ОБА чекера
    #   (и mypy, и pyright). Код в скобках — необязателен, но делает
    #   подавление точечным (глушит только эту одну проверку, а не
    #   вообще все на этой строке).


def broken_on_purpose_pyright_only() -> int:
    """То же самое, но специфичным для pyright комментарием."""
    return "not an int"  # pyright: ignore[reportReturnType]
    # ^ `# pyright: ignore[код]` — понимает ТОЛЬКО pyright. Если в
    #   проекте используется и mypy, эта строка для mypy останется
    #   обычной ошибкой — он не знает про pyright-специфичный синтаксис.


# ПРАВИЛО (уже действует в этом репозитории, см. auto memory):
# `# type: ignore` допустим ТОЛЬКО для намеренно "сломанного" кода
# в демо-целях, всегда с комментарием "намеренно" и почему. Для
# настоящих несоответствий типов — это костыль, а не решение; чинить
# нужно причину, а не подавлять симптом.


# ════════════════════════════════════════════════════════════════════════
# 8. Код возврата (exit code) — зачем он нужен для CI
# ════════════════════════════════════════════════════════════════════════
# И mypy, и pyright — обычные консольные программы. Если ошибок нет —
# они завершаются с кодом 0 ("успех"). Если ошибки есть — с кодом,
# отличным от 0 ("провал"). Это не влияет на то, что видно в
# терминале, но критично для автоматизации:
#
#   npx pyright && echo "typecheck OK"     # echo выполнится, только
#                                            # если pyright вернул 0
#
# В PowerShell код возврата последней команды — в переменной
# `$LASTEXITCODE`; в bash — в `$?`. Именно на этом механизме строятся
# CI-пайплайны (GitHub Actions и т.п.): шаг "проверить типы" помечается
# красным ИМЕННО потому, что процесс чекера вышел с ненулевым кодом,
# а не потому, что кто-то прочитал текст вывода.
