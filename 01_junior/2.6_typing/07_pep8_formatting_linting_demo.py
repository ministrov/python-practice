# ════════════════════════════════════════════════════════════════════════
# 1. Линтер vs форматтер vs чекер типов — три РАЗНЫХ инструмента
# ════════════════════════════════════════════════════════════════════════
#   Чекер типов (mypy/pyright, тема 3) — проверяет СООТВЕТСТВИЕ ТИПОВ:
#     "эта переменная объявлена как int, а ты пишешь в неё str"
#
#   Линтер (ruff, flake8) — проверяет КАЧЕСТВО КОДА безотносительно
#     типов: неиспользуемый импорт, необъявленная переменная, голый
#     `except:`, изменяемое значение по умолчанию (`def f(x=[])`),
#     нарушения PEP 8 (длина строки, пробелы, именование)
#
#   Форматтер (black, ruff format) — НЕ ищет ошибки, а ПЕРЕПИСЫВАЕТ
#     код в единый стиль: расставляет пробелы, переносит длинные
#     строки, единообразно расставляет кавычки. Ничего не "чинит" по
#     смыслу — просто причёсывает внешний вид
#
# Все три работают независимо и часто используются ВМЕСТЕ в одном
# проекте: mypy/pyright ловит логические ошибки типов, ruff — ловит
# code smell, black/ruff format — убирает споры про стиль форматирования
# из код-ревью (форматирование решает инструмент, а не человек).


# ════════════════════════════════════════════════════════════════════════
# 2. ruff vs black — что делает каждый
# ════════════════════════════════════════════════════════════════════════
#   ruff   — написан на Rust, очень быстрый. Изначально был ТОЛЬКО
#            линтером (заменяет flake8 + isort + десятки плагинов
#            одним инструментом), сейчас умеет ЕЩЁ и форматировать
#            (`ruff format` — форматтер, совместимый по стилю с black)
#   black  — форматтер (только форматирование, без линтинга).
#            Философия: "неоспариваемый" стиль — почти нет настроек,
#            чтобы в команде не спорили, как форматировать код
#
# На практике многие новые проекты используют ТОЛЬКО ruff (и как
# линтер, и как форматтер) — один инструмент вместо двух-трёх. black
# по-прежнему широко распространён в более старых проектах.


# ════════════════════════════════════════════════════════════════════════
# 3. Установка и запуск
# ════════════════════════════════════════════════════════════════════════
#     pip install ruff
#
#     ruff check .              # линтинг: найти проблемы во всём проекте
#     ruff check путь/файл.py   # линтинг одного файла
#     ruff format .             # форматирование всего проекта
#     ruff format путь/файл.py  # форматирование одного файла
#
#     pip install black
#     black .                   # форматирование всего проекта
#     black --check .           # только проверить, ничего не менять
#                                 # (полезно в CI — упадёт, если код
#                                 # не отформатирован)


# ════════════════════════════════════════════════════════════════════════
# 4. Конфигурация — pyproject.toml
# ════════════════════════════════════════════════════════════════════════
# И ruff, и black читают настройки из СЕКЦИЙ одного и того же файла
# pyproject.toml в корне проекта (в отличие от mypy/pyright, у которых
# СВОИ отдельные конфиг-файлы — mypy.ini, pyrightconfig.json):
#
#     [tool.ruff]
#     line-length = 79          # как в PEP8_STYLE_GUIDE.md этого репо
#     target-version = "py312"
#
#     [tool.ruff.lint]
#     select = ["E", "F", "W"]  # какие группы правил включить
#
#     [tool.black]
#     line-length = 79
#
# В этом репозитории уже есть `PEP8_STYLE_GUIDE.md` — свод правил,
# которым весь код следует ВРУЧНУЮ. `[tool.ruff]` в pyproject.toml —
# это тот же свод правил, но проверяемый автоматически, а не на глаз.


# ════════════════════════════════════════════════════════════════════════
# 5. Как читать вывод ruff — коды правил
# ════════════════════════════════════════════════════════════════════════
# Пример вывода:
#
#     файл.py:12:1: F401 'os' imported but unused
#     файл.py:34:80: E501 line too long (85 > 79 characters)
#     файл.py:8:5: F841 local variable 'result' is assigned to but
#     never used
#
# Префикс кода — откуда правило:
#   E/W  — pycodestyle (сам PEP 8: пробелы, длина строк, отступы)
#   F    — pyflakes (логические проблемы: неиспользуемый импорт,
#          необъявленное имя, недостижимый код)
#   B    — flake8-bugbear (типичные баги: мутабельный default,
#          `except Exception: pass` и т.п.)
#
# Знакомые примеры из уже пройденного в этом репозитории:
#   - `def f(target=None): if target is None: target = []` (Блок 2.3,
#     тема 1) — ruff с правилом B006 нашёл бы ИМЕННО эту ловушку
#     мутабельного default'а автоматически, до того как её объяснили
#     вручную
#   - неиспользуемые импорты `ABC`/`abstractmethod`/`IntEnum`/`auto`,
#     которые в этом репо ловил pyright (`reportUnusedImport`,
#     сеансы 26–27) — ruff нашёл бы то же самое кодом F401


# ════════════════════════════════════════════════════════════════════════
# 6. Автофикс — ruff check --fix
# ════════════════════════════════════════════════════════════════════════
#     ruff check --fix .
#
# Часть правил ruff умеет исправлять САМ (неиспользуемые импорты
# просто удаляются, порядок импортов пересортировывается). Часть
# правил (например, F841 — неиспользуемая переменная) НЕ исправляется
# автоматически — инструмент не знает, баг это или переменная нужна
# для читаемости, поэтому только указывает на строку.
#
# ВАЖНО: `--fix` меняет файлы НА ДИСКЕ. Как и с `git`, перед автофиксом
# стоит сначала посмотреть, что он собирается менять (`ruff check .`
# без `--fix` — это просто отчёт, файлы не трогает).


# ════════════════════════════════════════════════════════════════════════
# 7. Этот репозиторий уже следует PEP 8 — что изменилось бы с линтером
# ════════════════════════════════════════════════════════════════════════
# CLAUDE.md этого репозитория требует PEP 8 (`PEP8_STYLE_GUIDE.md`) на
# каждый файл, и до сих пор это проверялось ВРУЧНУЮ — либо мной при
# код-ревью, либо через `pyright --strict` (который ловит СВЯЗАННЫЕ
# с типами последствия несоблюдения стиля, например неиспользуемые
# импорты, но не длину строки и не двойные пробелы вокруг оператора).
#
# `ruff check .`, запущенный на весь `01_junior/`, добавил бы
# АВТОМАТИЧЕСКУЮ проверку именно PEP 8-специфичных вещей: длина строк
# >79 символов, лишние пробелы, неконсистентные отступы — то, что
# сейчас проверяется на глаз при чтении кода.
