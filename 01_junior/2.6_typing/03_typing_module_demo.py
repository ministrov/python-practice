"""
Блок 2.6.2: Демо — модуль typing (Any, Callable, Iterable, Sequence, TypedDict)
════════════════════════════════════════════════════════════════════════
Темы:
  1. Any — полное отключение проверки типа для значения (когда и почему
     этого лучше избегать)
  2. Callable — аннотация "это функция с такой-то сигнатурой"
  3. Iterable vs Sequence vs list — абстрактные типы параметров против
     конкретных типов возврата
  4. TypedDict — словарь с ФИКСИРОВАННЫМ набором строковых ключей и
     разными типами значений (в отличие от dict[str, X])
"""

from typing import Any, Callable, Iterable, Sequence, TypedDict


# ════════════════════════════════════════════════════════════════════════
# 1. Any — полное отключение проверки типа
# ════════════════════════════════════════════════════════════════════════
# `Any` говорит статическому чекеру: "не проверяй этот тип вообще,
# разрешено ЛЮБОЕ значение и ЛЮБАЯ операция над ним". Это НЕ то же самое,
# что "тип неизвестен пока" — это буквально выключатель проверки.
# Использовать стоит только на границе с непитипизированным кодом
# (например, `json.loads()` возвращает Any, потому что заранее не
# известно, что за JSON пришёл).


def parse_json_like(raw: dict[str, Any]) -> str:
    """raw может содержать значения любых типов — JSON так и работает."""
    return str(raw.get("name", "unknown"))


print(parse_json_like({"name": "Ann", "age": 25, "active": True}))

# ПРОБЛЕМА Any: он "заразен" — если функция возвращает Any, а мы
# используем результат дальше, pyright --strict перестаёт проверять
# ВСЮ последующую цепочку. Поэтому Any — последний вариант, не первый.
# Если тип на самом деле "что угодно из известного набора" — это Union
# (X | Y), а не Any.


# ════════════════════════════════════════════════════════════════════════
# 2. Callable — аннотация "это функция с такой сигнатурой"
# ════════════════════════════════════════════════════════════════════════
# Callable[[типы параметров], тип_результата] — используется, когда
# параметр или возвращаемое значение — это САМА функция (например,
# для колбэков, стратегий, декораторов).


def apply_twice(func: Callable[[int], int], value: int) -> int:
    """Применяет func к value два раза подряд."""
    return func(func(value))


def increment(n: int) -> int:
    return n + 1


print(apply_twice(increment, 5))  # 5 -> 6 -> 7


# Callable[..., X] — сигнатура параметров не важна (любая), важен
# только тип результата.
def run_and_log(func: Callable[..., Any]) -> None:
    """Вызывает func без аргументов и печатает результат."""
    print("Результат:", func())


run_and_log(lambda: 42)


# ════════════════════════════════════════════════════════════════════════
# 3. Iterable vs Sequence vs list — абстрактные типы параметров
# ════════════════════════════════════════════════════════════════════════
# Правило "be liberal in what you accept, conservative in what you
# return" (Постел): ПАРАМЕТРЫ функции стоит типизировать максимально
# АБСТРАКТНО (принимай минимум требований), а ВОЗВРАЩАЕМОЕ значение —
# максимально КОНКРЕТНО (обещай максимум гарантий).
#
#   Iterable[X] — можно пройтись циклом `for`, и всё. Нельзя взять
#                 len(), нельзя обратиться по индексу [0], нельзя
#                 пройти дважды (если это генератор).
#   Sequence[X] — можно len(), индексация [i], срезы [i:j], цикл,
#                 гарантированно можно проходить много раз.
#                 list, tuple, str — всё это Sequence.
#   list[X]     — Sequence + ещё и ИЗМЕНЯЕМЫЙ (append, remove, [i] = ...)


def sum_all(numbers: Iterable[float]) -> float:
    """Принимает ЛЮБОЙ перебираемый объект: list, tuple, генератор..."""
    return sum(numbers)


print(sum_all([1.0, 2.0, 3.0]))  # list — тоже Iterable
print(sum_all((1.0, 2.0, 3.0)))  # tuple — тоже Iterable
print(sum_all(x * 1.0 for x in range(4)))  # генератор — тоже Iterable


def first_and_last(items: Sequence[str]) -> tuple[str, str]:
    """Нужна индексация [0] и [-1] — Iterable для этого недостаточно."""
    return (items[0], items[-1])


print(first_and_last(["a", "b", "c"]))
print(first_and_last(("x", "y")))  # tuple тоже подходит — это Sequence

# Если бы first_and_last принимала Iterable[str], pyright --strict
# отказался бы компилировать items[0] — у Iterable нет __getitem__.


# ════════════════════════════════════════════════════════════════════════
# 4. TypedDict — словарь с фиксированными ключами и разными типами
# ════════════════════════════════════════════════════════════════════════
# dict[str, X] требует, чтобы ВСЕ значения были одного типа X.
# Но часто нужен словарь-запись с фиксированными ключами и РАЗНЫМИ
# типами значений на каждый ключ (как строка в таблице БД или JSON
# со известной схемой). Для этого — TypedDict.


class UserRecord(TypedDict):
    name: str
    age: int
    is_active: bool


def describe_user(user: UserRecord) -> str:
    """Все три ключа обязательны и типизированы по отдельности."""
    status = "активен" if user["is_active"] else "неактивен"
    return f"{user['name']}, {user['age']} лет, {status}"


ann: UserRecord = {"name": "Ann", "age": 25, "is_active": True}
print(describe_user(ann))

# pyright --strict проверит ВСЁ:
#   - что присутствуют все ключи ("name", "age", "is_active")
#   - что нет лишних ключей
#   - что тип каждого значения совпадает с объявленным в классе
# Обычный dict[str, str | int | bool] так не смог бы — он разрешил бы
# любой набор ключей и перепутанные типы значений между ключами.
