# ════════════════════════════════════════════════════════════════════════
# 1. Проблема: почему нельзя ставить пакеты глобально
# ════════════════════════════════════════════════════════════════════════
# У тебя на компьютере ОДИН Python (или несколько версий, но не суть).
# Если ставить пакеты командой `pip install X` без venv, они попадают
# в ОДНО общее место — site-packages ЭТОЙ установки Python, доступное
# ВСЕМ проектам сразу.
#
# Проблема возникает, когда у двух проектов на компьютере — РАЗНЫЕ
# требования к версии одного и того же пакета:
#
#   Проект A требует  Django==4.2
#   Проект B требует  Django==5.1
#
# Оба не могут быть установлены глобально одновременно — второй
# `pip install` просто заменит первую версию. Один из проектов
# перестанет работать. Это и называют "dependency hell".


# ════════════════════════════════════════════════════════════════════════
# 2. venv — изолированное окружение для ОДНОГО проекта
# ════════════════════════════════════════════════════════════════════════
# `venv` (virtual environment) — модуль стандартной библиотеки Python
# (ничего дополнительно ставить не нужно), который создаёт ОТДЕЛЬНУЮ
# копию интерпретатора и папки для пакетов — ТОЛЬКО для одного
# проекта. Пакеты, установленные внутри venv проекта A, НЕ видны
# проекту B и НЕ видны системному Python.
#
# Практика: у КАЖДОГО Python-проекта — своя папка venv, обычно
# называется `.venv` или `venv` в корне проекта.


# ════════════════════════════════════════════════════════════════════════
# 3. Создание, активация, деактивация
# ════════════════════════════════════════════════════════════════════════
#     python -m venv .venv          # создать venv в папке .venv
#
# Активация — команда РАЗНАЯ в зависимости от терминала:
#
#     .venv\Scripts\Activate.ps1    # PowerShell (Windows)
#     .venv\Scripts\activate.bat    # cmd.exe (Windows)
#     source .venv/bin/activate     # bash/zsh (Linux/macOS, Git Bash)
#
# После активации приглашение терминала меняется — появляется префикс
# `(.venv)` перед строкой ввода. Это значит: команды `python` и `pip`
# теперь указывают на интерпретатор и пакеты ВНУТРИ `.venv`, а не на
# системные.
#
#     deactivate                    # выйти из venv, вернуться к
#                                     # системному Python (одна и та
#                                     # же команда для всех терминалов)


# ════════════════════════════════════════════════════════════════════════
# 4. pip внутри venv — пакеты видит только этот проект
# ════════════════════════════════════════════════════════════════════════
# После активации venv команда `pip install` ставит пакет ТОЛЬКО
# внутрь `.venv` этого проекта:
#
#     (.venv) pip install requests
#     (.venv) pip list                # что установлено в ЭТОМ venv
#
# Деактивируешь venv — `import requests` в системном Python (без
# активного venv) больше не найдёт этот пакет. Так и достигается
# изоляция: у каждого проекта — свой независимый набор пакетов.


# ════════════════════════════════════════════════════════════════════════
# 5. requirements.txt — список зависимостей проекта
# ════════════════════════════════════════════════════════════════════════
# venv не коммитится в git (следующий раздел — почему), значит, когда
# кто-то ещё клонирует проект, у него venv ПУСТОЙ — без пакетов.
# `requirements.txt` — текстовый файл со списком пакетов и версий,
# который позволяет восстановить ТОЧНО такой же набор одной командой:
#
#     (.venv) pip freeze > requirements.txt
#         # сохраняет ВСЕ установленные пакеты с точными версиями,
#         # например:
#         #   requests==2.31.0
#         #   pyright==1.1.413
#
#     (.venv) pip install -r requirements.txt
#         # у другого разработчика (или на сервере, или в CI) —
#         # ставит РОВНО те же версии одной командой
#
# Файл `requirements.txt` КОММИТИТСЯ в git (в отличие от самой папки
# venv) — это часть кода проекта, описывающая его зависимости.


# ════════════════════════════════════════════════════════════════════════
# 6. .gitignore — venv никогда не коммитится
# ════════════════════════════════════════════════════════════════════════
# Папка venv может весить сотни мегабайт и полностью восстановима из
# requirements.txt за секунды — коммитить её в git бессмысленно и
# раздувает репозиторий. `.gitignore` этого репозитория уже содержит
# нужные строки:
#
#     venv/
#     env/
#     ENV/
#
# (Технически venv здесь принято называть `.venv/` с точкой — стоит
# при случае добавить и такую строку в `.gitignore`, если создавать
# venv с этим именем.)


# ════════════════════════════════════════════════════════════════════════
# 7. Как это было (не) сделано в этом самом репозитории (тема 3)
# ════════════════════════════════════════════════════════════════════════
# В теме 3 этого блока `pip install ruff` был выполнен БЕЗ активного
# venv — пакет установился ГЛОБАЛЬНО, в site-packages системного
# Python. Для учебного репозитория с одним-единственным проектом это
# не создаёт проблем (конфликтовать не с чем). Но именно так на
# практике и рождается "dependency hell": если позже появится второй
# проект, которому нужна ДРУГАЯ версия ruff или другого пакета — они
# начнут конфликтовать за одно и то же глобальное место.
#
# Правильно было бы: создать `.venv` В ЭТОМ репозитории, активировать
# его, и только потом ставить `ruff`/`pyright`/`mypy` — тогда они были
# бы изолированы именно для этого проекта.


# ════════════════════════════════════════════════════════════════════════
# 8. Современные альтернативы: uv, poetry (обзорно, без деталей)
# ════════════════════════════════════════════════════════════════════════
# `venv` + `pip` + `requirements.txt` — стандарт, входит в сам Python,
# работает везде. У него есть более новые замены, которые решают те же
# задачи быстрее и с доп. возможностями (точная фиксация версий всего
# дерева зависимостей, а не только верхнего уровня):
#
#   uv      — написан на Rust (та же команда, что делает ruff),
#             в разы быстрее pip, одна команда `uv venv` + `uv pip`
#   poetry  — более старый и распространённый инструмент, добавляет
#             файл `pyproject.toml` (тот же файл, что уже появился в
#             этом репо для ruff) как единый источник правды о
#             зависимостях и версии проекта
#
# Для этого учебного репозитория остаёмся на `venv`/`pip` — это
# базовый стандарт, который стоит знать до всех надстроек над ним.
