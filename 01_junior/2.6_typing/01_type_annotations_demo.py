"""
Блок 2.6.1: Демо — аннотации типов
════════════════════════════════════════════════════════════════════════
Темы:
  1. Зачем формальная типизация — то, что уже писалось интуитивно с
     блока 2.1, теперь называется словами и разбирается подробно
  2. Параметризованные generic-коллекции: list[int], dict[str, int],
     tuple[int, ...], set[str]
  3. Аннотации НЕ проверяются в рантайме — только статическим чекером
  4. Optional[X] и X | None — один и тот же смысл, разный синтаксис
  5. Union[X, Y] и X | Y — несколько разрешённых типов
  6. Вложенные generic-типы: list[dict[str, int]]
"""


# ════════════════════════════════════════════════════════════════════════
# 1. Зачем формальная типизация
# ════════════════════════════════════════════════════════════════════════
# Аннотации типов (`def f(x: int) -> str:`) уже писались с блока 2.3
# (функции) — но там это было "просто синтаксис, который требует
# Pylance". Сейчас — отдельная тема: ЧТО можно писать в аннотациях,
# кроме простых int/str/bool, и КАК это помогает находить баги ДО
# запуска программы.

def greet(name: str) -> str:
    """Простая аннотация: name — обязательно str, результат — str."""
    return f"Привет, {name}!"


print(greet("Антон"))


# ════════════════════════════════════════════════════════════════════════
# 2. Параметризованные generic-коллекции
# ════════════════════════════════════════════════════════════════════════
# Голое `list` или `dict` в аннотации говорит ТОЛЬКО "это список/словарь",
# но не говорит, ЧЕГО. Под pyright --strict голый list без параметра —
# ошибка (`reportMissingTypeArgument`). Нужно указывать содержимое
# в квадратных скобках — это и называется generic-параметризация.

def total_price(prices: list[float]) -> float:
    """prices — список ИМЕННО float, не любых объектов."""
    return sum(prices)


def count_by_word(words: list[str]) -> dict[str, int]:
    """Принимает список str, возвращает словарь str -> int."""
    result: dict[str, int] = {}
    for word in words:
        result[word] = result.get(word, 0) + 1
    return result


print(total_price([9.99, 4.5, 12.0]))
print(count_by_word(["a", "b", "a", "c", "b", "a"]))

# Другие частые generic-коллекции:
#   tuple[int, ...]      — кортеж ЛЮБОЙ длины, все элементы int
#   tuple[int, str, bool] — кортеж РОВНО из 3 элементов, типы по позиции
#   set[str]             — множество строк

point: tuple[int, int] = (3, 5)          # кортеж ровно из 2 int
scores: tuple[int, ...] = (10, 20, 30)   # кортеж любой длины из int
unique_names: set[str] = {"Ann", "Bob"}

print(point, scores, unique_names)


# ════════════════════════════════════════════════════════════════════════
# 3. Аннотации НЕ проверяются в рантайме
# ════════════════════════════════════════════════════════════════════════
# Это уже разбиралось в Блоке 2.5 (Вопрос 3 микротеста, про
# Manager.salary) — но здесь повторяется отдельно, т.к. это КЛЮЧЕВОЙ
# факт всей темы типизации. Python не останавливает выполнение, если
# в переменную с аннотацией `int` положить `str` — аннотация это
# ПОДСКАЗКА для человека и для статических чекеров (pyright, mypy),
# а не проверка, которую выполняет сам интерпретатор.

wrong: int = "это не число"  # type: ignore[assignment]  # намеренно: показываем, что рантайм не проверяет
print(wrong, type(wrong))
# pyright --strict ЗДЕСЬ бы ошибку показал (reportAssignmentType),
# но в реальном коде так писать нельзя — из-за # type: ignore выше
# эта конкретная строка не считается за ошибку. Без # type: ignore
# pyright бы её поймал ДО запуска, а python — только когда код дойдёт
# до места, где реальный тип начнёт мешать (например, wrong + 1 упадёт
# TypeError-ом в рантайме, а pyright предсказал бы это заранее).


# ════════════════════════════════════════════════════════════════════════
# 4. Optional[X] и X | None
# ════════════════════════════════════════════════════════════════════════
# "Значение либо есть тип X, либо его нет вообще (None)" — очень частый
# случай (например, поиск, который может ничего не найти). Два способа
# написать одно и то же:
#   from typing import Optional
#   def find(...) -> Optional[str]: ...      # старый стиль
#   def find(...) -> str | None: ...          # современный (3.10+),
#                                              # ничего импортировать не надо
# В этом репозитории (Python 3.12+) — используем `X | None`.

def find_first_even(numbers: list[int]) -> int | None:
    """Возвращает первое чётное число или None, если такого нет."""
    for number in numbers:
        if number % 2 == 0:
            return number
    return None


print(find_first_even([1, 3, 5, 8, 9]))
print(find_first_even([1, 3, 5]))

# ВАЖНО: `str | None` — это аннотация ТИПА (что можно вернуть), а не
# значение по умолчанию. Это разные вещи:
#   def f(x: str | None = None) -> None: ...
#          ^^^^^^^^^^^^   ^^^^ значение по умолчанию — отдельно, через =


# ════════════════════════════════════════════════════════════════════════
# 5. Union[X, Y] и X | Y — несколько разрешённых типов
# ════════════════════════════════════════════════════════════════════════
# `Optional[X]` — частный случай Union: `Optional[X]` == `Union[X, None]`
# == `X | None`. Но Union годится для ЛЮБОЙ комбинации типов, не только
# с None:
#   from typing import Union
#   def parse(raw: str) -> Union[int, float]: ...   # старый стиль
#   def parse(raw: str) -> int | float: ...           # современный

def parse_number(raw: str) -> int | float:
    """Возвращает int, если строка целая, иначе float."""
    if "." in raw:
        return float(raw)
    return int(raw)


print(parse_number("42"), type(parse_number("42")))
print(parse_number("3.14"), type(parse_number("3.14")))


# ════════════════════════════════════════════════════════════════════════
# 6. Вложенные generic-типы
# ════════════════════════════════════════════════════════════════════════
# generic-параметры можно вкладывать друг в друга произвольно глубоко —
# ровно так же, как вкладываются сами структуры данных.

def group_scores_by_student(
    records: list[tuple[str, int]],
) -> dict[str, list[int]]:
    """records: [(имя, оценка), ...] -> {имя: [оценки, ...]}."""
    grouped: dict[str, list[int]] = {}
    for name, score in records:
        grouped.setdefault(name, []).append(score)
    return grouped


data = [("Ann", 5), ("Bob", 4), ("Ann", 4), ("Bob", 5), ("Ann", 5)]
print(group_scores_by_student(data))
