from contextlib import contextmanager, suppress
from collections.abc import Generator


# ════════════════════════════════════════════════════════════════════════
# 1. Проблема: гарантированная очистка ресурса
# ════════════════════════════════════════════════════════════════════════
# Ресурс (файл, соединение с БД, лок) нужно ЗАКРЫТЬ независимо от того,
# упал код внутри или нет. Без try/finally очистка легко теряется, если
# между открытием и закрытием что-то бросит исключение.


class ManualResource:
    """Условный "ресурс" — просто печатает открытие/закрытие."""

    def __init__(self, name: str) -> None:
        self.name = name

    def open(self) -> None:
        print(f"[{self.name}] открыт")

    def close(self) -> None:
        print(f"[{self.name}] закрыт")


def use_resource_manually_ok() -> None:
    res = ManualResource("ручной-ok")
    res.open()
    try:
        print(f"[{res.name}] работа")
    finally:
        res.close()  # выполнится даже при исключении внутри try


use_resource_manually_ok()
# [ручной-ok] открыт
# [ручной-ok] работа
# [ручной-ok] закрыт


# ════════════════════════════════════════════════════════════════════════
# 2. Протокол with: __enter__ и __exit__
# ════════════════════════════════════════════════════════════════════════
# `with выражение as имя:` — то же самое, что try/finally выше, но без
# ручного finally. Python сам вызывает два метода объекта:
#   __enter__(self)  — при входе в блок, результат идёт в `as имя`
#   __exit__(self, exc_type, exc_val, exc_tb) — при выходе, ВСЕГДА,
#     даже если внутри блока было исключение
# Уже знакомый пример: `with open(path) as f:` — файл сам себя
# закрывает через __exit__, даже если чтение упадёт посередине.


# ════════════════════════════════════════════════════════════════════════
# 3. Свой контекстный менеджер классом
# ════════════════════════════════════════════════════════════════════════
class ManagedResource:
    """Тот же ресурс, но управляется протоколом with."""

    def __init__(self, name: str) -> None:
        self.name = name

    def __enter__(self) -> "ManagedResource":
        print(f"[{self.name}] открыт (via __enter__)")
        return self  # то, что попадёт в `as res`

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc_val: BaseException | None,
        exc_tb: object,
    ) -> None:
        print(f"[{self.name}] закрыт (via __exit__)")


with ManagedResource("класс-ok") as res:
    print(f"[{res.name}] работа")
# [класс-ok] открыт (via __enter__)
# [класс-ok] работа
# [класс-ok] закрыт (via __exit__)


print()
try:
    with ManagedResource("класс-ошибка") as res:
        print(f"[{res.name}] работа")
        raise ValueError("что-то сломалось внутри with")
except ValueError as e:
    print(f"поймано снаружи: {e}")
# [класс-ошибка] открыт (via __enter__)
# [класс-ошибка] работа
# [класс-ошибка] закрыт (via __exit__)   <- __exit__ вызван, ХОТЯ упало
# поймано снаружи: что-то сломалось внутри with


# ════════════════════════════════════════════════════════════════════════
# 4. __exit__ и исключения — return True подавляет ошибку
# ════════════════════════════════════════════════════════════════════════
# Если внутри with произошло исключение, Python передаёт его детали в
# __exit__ через exc_type/exc_val/exc_tb (иначе все три — None).
# Что вернёт __exit__ — решает судьбу исключения:
#   вернул None / False (или ничего) — исключение летит дальше как обычно
#   вернул True                       — исключение ПОДАВЛЕНО, как будто
#                                        его не было
# Подавлять стоит осознанно — это легко спрятать реальный баг.


class SuppressingResource:
    """Пример: __exit__ гасит только ОДИН конкретный тип ошибки."""

    def __enter__(self) -> "SuppressingResource":
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc_val: BaseException | None,
        exc_tb: object,
    ) -> bool:
        if exc_type is ZeroDivisionError:
            print(f"погашено: {exc_val}")
            return True  # подавить именно эту ошибку
        return False  # остальные — пропустить дальше как есть


print()
with SuppressingResource():
    result = 1 / 0
print("код после with выполнился — ошибка была подавлена")
# погашено: division by zero
# код после with выполнился — ошибка была подавлена


# ════════════════════════════════════════════════════════════════════════
# 5. contextlib.contextmanager — тот же менеджер через генератор
# ════════════════════════════════════════════════════════════════════════
# Писать класс с __enter__/__exit__ ради простого "открыть — закрыть"
# часто избыточно. `@contextmanager` превращает ГЕНЕРАТОР в контекстный
# менеджер: код ДО yield — это __enter__, значение yield — то, что
# попадёт в `as`, код ПОСЛЕ yield — это __exit__. try/finally вокруг
# yield гарантирует очистку так же, как __exit__ гарантирован Python'ом.


@contextmanager
def managed_resource(name: str) -> Generator[str]:
    print(f"[{name}] открыт (via contextmanager)")
    try:
        yield name  # тут выполняется тело `with ... as name:`
    finally:
        print(f"[{name}] закрыт (via contextmanager)")


print()
with managed_resource("генератор-ok") as name:
    print(f"[{name}] работа")
# [генератор-ok] открыт (via contextmanager)
# [генератор-ok] работа
# [генератор-ok] закрыт (via contextmanager)


# ════════════════════════════════════════════════════════════════════════
# 6. contextlib.suppress — короткая замена except: pass
# ════════════════════════════════════════════════════════════════════════
# Частый паттерн: "попробовать, и если конкретная ошибка — просто
# проигнорировать". `suppress(*типы)` делает это в одну строку вместо
# try/except/pass.

print()
with suppress(FileNotFoundError):
    open("такого_файла_точно_нет.txt")
print("после suppress — программа не упала")
# после suppress — программа не упала


# ════════════════════════════════════════════════════════════════════════
# 7. Несколько менеджеров в одном with
# ════════════════════════════════════════════════════════════════════════
# `with A() as a, B() as b:` — эквивалент вложенных `with A() as a:
# with B() as b:`, но в одну строку. Порядок входа — слева направо,
# порядок выхода (закрытия) — справа налево (как со стеком).

print()
with (
    ManagedResource("внешний") as outer,
    ManagedResource("внутренний") as inner,
):
    print(f"работа с [{outer.name}] и [{inner.name}]")
# [внешний] открыт (via __enter__)
# [внутренний] открыт (via __enter__)
# работа с [внешний] и [внутренний]
# [внутренний] закрыт (via __exit__)   <- закрывается первым (последним открыт)
# [внешний] закрыт (via __exit__)


