# -*- coding: utf-8 -*-
"""
Блок 2.7.2: Демо — raise from, цепочки исключений, ExceptionGroup
════════════════════════════════════════════════════════════════════════
Темы:
  1. Проблема: поднять новую ошибку внутри except — что происходит с
     оригинальной ошибкой
  2. Неявная цепочка (__context__) — происходит САМА, без raise ... from
  3. raise ... from e — ЯВНАЯ цепочка ("прямая причина")
  4. raise ... from None — подавить цепочку целиком
  5. __cause__ и __context__ — как прочитать цепочку из кода
  6. ExceptionGroup и except* (Python 3.11+) — несколько ошибок сразу
"""


# ════════════════════════════════════════════════════════════════════════
# 1. Проблема: новая ошибка внутри except
# ════════════════════════════════════════════════════════════════════════
# Частый паттерн: поймали низкоуровневую ошибку (например, ValueError
# при разборе строки), хотим поднять более понятную вызывающему коду
# ошибку (например, "некорректные данные пользователя"). Но что
# происходит с ПЕРВОЙ ошибкой, когда мы поднимаем ВТОРУЮ?


class InvalidUserDataError(Exception):
    """Ошибка уровня приложения — понятна вызывающему коду."""


def parse_age_naive(raw: str) -> int:
    try:
        return int(raw)
    except ValueError:
        # noqa: B904 — намеренно без `from`, демонстрация НЕЯВНОЙ
        # цепочки (раздел 2); ruff предлагает `from err`/`from None`
        raise InvalidUserDataError(f"Некорректный возраст: {raw!r}")  # noqa: B904


try:
    parse_age_naive("двадцать")
except InvalidUserDataError as e:
    print(f"Поймано: {e}")
    print(f"__context__: {e.__context__!r}")
    # Оригинальный ValueError НЕ потерян — Python сохранил его САМ,
    # даже без явного raise ... from. Это и есть НЕЯВНАЯ цепочка.


# ════════════════════════════════════════════════════════════════════════
# 2. Неявная цепочка (__context__) — происходит сама
# ════════════════════════════════════════════════════════════════════════
# Если внутри except-блока поднять НОВОЕ исключение (просто `raise
# ДругаяОшибка(...)`, без `from`), Python АВТОМАТИЧЕСКИ запоминает
# исходное исключение в атрибуте `__context__` нового. Если такое
# исключение долетит до верха программы необработанным, traceback
# покажет ОБА, с пометкой:
#
#   During handling of the above exception, another exception occurred:
#
# Это может выглядеть как "два traceback подряд" и сбивать с толку —
# непонятно, это одна ошибка или две разные проблемы одна за другой.


# ════════════════════════════════════════════════════════════════════════
# 3. raise ... from e — явная цепочка ("прямая причина")
# ════════════════════════════════════════════════════════════════════════
# `raise НоваяОшибка(...) from original_error` говорит явно: "новая
# ошибка ПРОИЗОШЛА ИЗ-ЗА этой". Записывается в атрибут `__cause__`
# (не `__context__`). Необработанный traceback покажет более точную
# формулировку:
#
#   The above exception was the direct cause of the following exception:
#
# Разница на практике небольшая (оба варианта сохраняют оригинал), но
# `from e` — явная документация НАМЕРЕНИЯ: "я знаю, что это следствие
# именно этой ошибки", а не "так вышло само".


def parse_age_explicit(raw: str) -> int:
    try:
        return int(raw)
    except ValueError as e:
        raise InvalidUserDataError(f"Некорректный возраст: {raw!r}") from e


try:
    parse_age_explicit("тридцать")
except InvalidUserDataError as e:
    print(f"\n__cause__: {e.__cause__!r}")
    print(f"__context__: {e.__context__!r}")
    # __cause__ и __context__ оба указывают на один и тот же ValueError
    # — `from e` заполняет ОБА, но именно __cause__ говорит "явно
    # указано программистом", а не "выведено автоматически"


# ════════════════════════════════════════════════════════════════════════
# 4. raise ... from None — подавить цепочку целиком
# ════════════════════════════════════════════════════════════════════════
# Иногда оригинальная ошибка — деталь РЕАЛИЗАЦИИ, неинтересная тому,
# кто вызывает функцию (например, внутри библиотеки менялся способ
# парсинга — какая конкретно внутренняя ошибка произошла, вызывающему
# коду знать не нужно и может запутать). `from None` убирает цепочку
# ИЗ TRACEBACK — traceback покажет ТОЛЬКО новую ошибку.
#
# ТОНКОСТЬ (легко предположить неверно): `from None` устанавливает
# __cause__ = None и __suppress_context__ = True, но САМ __context__
# остаётся заполненным оригинальной ошибкой — просто traceback его не
# печатает из-за __suppress_context__. Оригинал не "стёрт", а именно
# "спрятан от печати". Если нужно — можно достать его из кода вручную.


def parse_age_clean(raw: str) -> int:
    try:
        return int(raw)
    except ValueError:
        raise InvalidUserDataError(f"Некорректный возраст: {raw!r}") from None


try:
    parse_age_clean("сорок")
except InvalidUserDataError as e:
    print(f"\n__cause__: {e.__cause__!r}")  # None
    print(f"__context__: {e.__context__!r}")  # заполнен! просто скрыт
    print(f"__suppress_context__: {e.__suppress_context__!r}")  # True


# ════════════════════════════════════════════════════════════════════════
# 5. Итог: когда что использовать
# ════════════════════════════════════════════════════════════════════════
#   raise Новая(...)             — ОК для быстрых скриптов; цепочка
#                                    сохранится сама (__context__), но
#                                    без явного намерения в коде
#   raise Новая(...) from e      — ЛУЧШАЯ ПРАКТИКА в прикладном коде:
#                                    явно документирует "это следствие
#                                    именно этой ошибки"
#   raise Новая(...) from None   — когда оригинал — деталь реализации,
#                                    которая не должна "утекать"
#                                    наружу и путать вызывающего


# ════════════════════════════════════════════════════════════════════════
# 6. ExceptionGroup и except* (Python 3.11+) — несколько ошибок сразу
# ════════════════════════════════════════════════════════════════════════
# До сих пор один try мог поймать только ОДНО исключение за раз — та
# операция, что упала первой, останавливала весь блок. Но иногда
# нужно выполнить НЕСКОЛЬКО независимых операций и собрать ВСЕ ошибки
# сразу (например, провалидировать 5 полей формы и показать ошибки по
# всем сразу, а не только по первому же).
#
# `ExceptionGroup` — контейнер, который упаковывает НЕСКОЛЬКО
# исключений в одно. `except*` (со звёздочкой — отдельный синтаксис,
# не опечатка) — ловит из группы только исключения нужного типа,
# остальные группа передаёт дальше.


def validate_form(fields: dict[str, str]) -> None:
    """Собирает ВСЕ ошибки валидации сразу, а не только первую."""
    errors: list[Exception] = []
    if not fields.get("name"):
        errors.append(ValueError("имя обязательно"))
    if not fields.get("email"):
        errors.append(ValueError("email обязателен"))
    if "age" in fields and not fields["age"].isdigit():
        errors.append(TypeError("возраст должен быть числом"))

    if errors:
        raise ExceptionGroup("ошибки валидации формы", errors)


try:
    validate_form({"age": "не число"})
except* ValueError as eg:
    print(f"\nValueError-и в группе: {[str(e) for e in eg.exceptions]}")
except* TypeError as eg:
    print(f"TypeError-ы в группе: {[str(e) for e in eg.exceptions]}")
    # оба except* сработают по очереди — каждый забирает СВОИ типы
    # из группы; обычный `except ValueError` так делать не умеет
