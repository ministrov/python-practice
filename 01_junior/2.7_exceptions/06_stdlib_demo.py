# ════════════════════════════════════════════════════════════════════════
# 6. itertools — эффективная работа с итераторами
# ════════════════════════════════════════════════════════════════════════
letters = ["a", "b", "c"]
numbers = [1, 2, 3]

# соединить без вложенных циклов
chained = list(itertools.chain(letters, numbers))
print(f"\nchain: {chained}")

# все комбинации (декартово произведение)
pairs = list(itertools.product(letters, numbers))
print(f"product (первые 3): {pairs[:3]}")

grouped_data = [("a", 1), ("a", 2), ("b", 3)]
grouped = {
    key: [v for _, v in group]
    for key, group in itertools.groupby(grouped_data, key=lambda pair: pair[0])
}
print(f"groupby: {grouped}")
# chain: ['a', 'b', 'c', 1, 2, 3]
# product (первые 3): [('a', 1), ('a', 2), ('a', 3)]
# groupby: {'a': [1, 2], 'b': [3]}

# ЛОВУШКА groupby: работает только на УЖЕ отсортированных по ключу
# данных (группирует только СОСЕДНИЕ одинаковые ключи подряд) — если
# данные не отсортированы, одинаковые ключи в разных местах списка
# попадут в РАЗНЫЕ группы.


# ════════════════════════════════════════════════════════════════════════
# 7. functools — reduce, partial, lru_cache
# ════════════════════════════════════════════════════════════════════════
def add(a: int, b: int) -> int:
    return a + b


# свернуть список в одно значение
total = functools.reduce(add, [1, 2, 3, 4], 0)
print(f"\nreduce (сумма): {total}")

add_ten = functools.partial(add, 10)  # "заморозить" первый аргумент
print(f"partial: {add_ten(5)}")


@functools.lru_cache(maxsize=None)
def slow_square(n: int) -> int:
    print(f"  считаю {n} ** 2...")
    return n**2


print(f"первый вызов: {slow_square(4)}")
print(f"второй вызов (из кэша, без печати 'считаю'): {slow_square(4)}")
# reduce (сумма): 10
# partial: 15
#   считаю 4 ** 2...
# первый вызов: 16
# второй вызов (из кэша, без печати 'считаю'): 16

# reduce почти всегда можно заменить обычным циклом или sum()/max() —
# используй, только если встроенной функции для операции нет.
# lru_cache — реальный инструмент бэкенда: кэширует результат функции
# по аргументам, полезно для дорогих чистых (без побочных эффектов)
# вычислений.
