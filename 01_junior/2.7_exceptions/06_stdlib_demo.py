# ════════════════════════════════════════════════════════════════════════
# 1. pathlib — пути к файлам
# ════════════════════════════════════════════════════════════════════════
# До pathlib пути собирали строками (os.path.join). Path — объект,
# пути строятся оператором `/`, работает одинаково на Windows и Linux.

here = Path(__file__).parent  # папка текущего файла
config_path = here / "configs" / "app.json"  # НЕ создаёт файл, просто путь

print(f"путь: {config_path}")
print(f"имя файла: {config_path.name}")
print(f"расширение: {config_path.suffix}")
print(f"родитель: {config_path.parent.name}")
print(f"существует ли: {config_path.exists()}")
# путь: .../2.7_exceptions/configs/app.json
# имя файла: app.json
# расширение: .json
# родитель: configs
# существует ли: False

# Частые операции: path.read_text()/write_text() — читают/пишут файл
# целиком без ручного open()/close(); path.glob("*.py") — найти файлы
# по маске; path.mkdir(parents=True, exist_ok=True) — создать папку
# (и родителей) без падения, если уже существует.


# ════════════════════════════════════════════════════════════════════════
# 2. datetime — дата и время
# ════════════════════════════════════════════════════════════════════════
today = date(2026, 8, 19)
now = datetime(2026, 8, 19, 14, 30, 0)

print(f"\nдата: {today}")
print(f"дата и время: {now}")
print(f"день недели (0=пн): {today.weekday()}")

deadline = date(2026, 9, 1)
days_left = (deadline - today).days  # разница дат — timedelta
print(f"дней до дедлайна: {days_left}")

in_two_weeks = now + timedelta(weeks=2)
print(f"через 2 недели: {in_two_weeks}")

formatted = now.strftime("%d.%m.%Y %H:%M")  # datetime -> строка
# строка -> datetime
parsed = datetime.strptime("19.08.2026 14:30", "%d.%m.%Y %H:%M")
print(f"отформатировано: {formatted}")
print(f"распарсено обратно: {parsed}")
# дата: 2026-08-19
# дата и время: 2026-08-19 14:30:00
# день недели (0=пн): 2
# дней до дедлайна: 13
# через 2 недели: 2026-09-02 14:30:00
# отформатировано: 19.08.2026 14:30
# распарсено обратно: 2026-08-19 14:30:00

# ВАЖНАЯ ЛОВУШКА бэкенда: datetime(...) без указания часового пояса —
# "наивный" (naive), не привязан ни к какому TZ. Для бэкенда обычно
# нужен "осведомлённый" (aware) datetime с explicit timezone (модуль
# zoneinfo, Python 3.9+) — иначе легко перепутать локальное время
# сервера с UTC. Здесь не углубляемся — просто предупреждение.


# ════════════════════════════════════════════════════════════════════════
# 3. json — сериализация/десериализация
# ════════════════════════════════════════════════════════════════════════
user = {"name": "Аня", "age": 25, "active": True, "tags": ["admin", "dev"]}

as_json = json.dumps(user, ensure_ascii=False, indent=2)
print(f"\n{as_json}")

back_to_dict = json.loads(as_json)
print(f"обратно в dict: {back_to_dict}")
print(f"тип: {type(back_to_dict)}")
# {
#   "name": "Аня",
#   ...
# }
# обратно в dict: {'name': 'Аня', 'age': 25, ...}
# тип: <class 'dict'>

# json.dumps умеет ТОЛЬКО базовые типы (dict, list, str, int, float,
# bool, None). date/datetime/set — упадут с TypeError, если не задать
# `default=` (функцию, которая превращает "непонятный" объект в
# что-то сериализуемое).


# ════════════════════════════════════════════════════════════════════════
# 4. re — регулярные выражения
# ════════════════════════════════════════════════════════════════════════
text = "Заказы: #101, #205, #3007"

ids = re.findall(r"#(\d+)", text)  # все совпадения группы
print(f"\nнайденные id: {ids}")

match = re.search(r"#(\d+)", text)  # первое совпадение (объект Match)
if match:
    print(f"первое совпадение целиком: {match.group(0)}")
    print(f"только группа (цифры): {match.group(1)}")

cleaned = re.sub(r"#\d+", "N", text)  # замена всех совпадений
print(f"после замены: {cleaned}")
# найденные id: ['101', '205', '3007']
# первое совпадение целиком: #101
# только группа (цифры): 101
# после замены: Заказы: N, N, N

# Для повторного использования одного паттерна — re.compile(pattern),
# результат переиспользуется без перекомпиляции каждый вызов.


