# -*- coding: utf-8 -*-
"""
Блок 2.7.5: Демо — logging (вместо print)
════════════════════════════════════════════════════════════════════════
Ознакомительная тема — база, без глубокого погружения в handlers/
formatters (это уже конфигурация конкретного проекта).

Темы:
  1. Проблема: почему print() не годится для бэкенда
  2. basicConfig — минимальная настройка, уровни логирования
  3. logging.getLogger(__name__) — логгер на модуль, не глобальный print
  4. Свой формат и отдельный логгер (без дублирования через root)
  5. Логирование исключений: logger.exception() внутри except
  6. handlers/formatters — обзорно, без кода
"""

import logging


# ════════════════════════════════════════════════════════════════════════
# 1. Проблема: почему print() не годится для бэкенда
# ════════════════════════════════════════════════════════════════════════
# print() — всегда одинаковый, без уровня важности (баг это или просто
# информация?), без времени события, без источника (какой модуль/файл
# это напечатал?). В проде print() нельзя выборочно отключить (нужны
# только ошибки — но не отладочные детали) и он не пишется в файл/
# систему мониторинга сам по себе. logging решает все четыре проблемы:
# уровни важности, автоматический timestamp, имя источника, настраиваемый
# вывод (консоль/файл/куда угодно) без изменения кода, который логирует.


# ════════════════════════════════════════════════════════════════════════
# 2. basicConfig — минимальная настройка, уровни логирования
# ════════════════════════════════════════════════════════════════════════
# 5 стандартных уровней, по возрастанию важности:
#   DEBUG < INFO < WARNING < ERROR < CRITICAL
# level=logging.INFO в basicConfig означает: показывать INFO и ВЫШЕ,
# DEBUG — отфильтруется, его не будет видно.

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    datefmt="%H:%M:%S",
)

logger = logging.getLogger(__name__)

logger.debug("это DEBUG — не покажется, уровень отфильтрован")
logger.info("сервер запущен на порту 8000")
logger.warning("свободное место на диске меньше 10%")
logger.error("не удалось подключиться к БД")
logger.critical("сервис недоступен, аварийное завершение")
# 12:34:56 [INFO] __main__: сервер запущен на порту 8000
# 12:34:56 [WARNING] __main__: свободное место на диске меньше 10%
# (в сообщении % можно писать как обычный символ, ЕСЛИ логгеру не
# передают позиционные аргументы для %-форматирования — экранирование
# %% нужно только когда есть args, например logger.warning("%s%%", n))
# 12:34:56 [ERROR] __main__: не удалось подключиться к БД
# 12:34:56 [CRITICAL] __main__: сервис недоступен, аварийное завершение
# (время будет отличаться при каждом запуске — это нормально; DEBUG
# строка не появится вообще — уровень INFO её отфильтровал)


# ════════════════════════════════════════════════════════════════════════
# 3. logging.getLogger(__name__) — логгер на модуль, не глобальный print
# ════════════════════════════════════════════════════════════════════════
# `__name__` — имя текущего модуля (см. Блок 2.4, тема "Модули"). Логгер,
# созданный через getLogger(__name__), в сообщениях сам печатает ИМЯ
# своего модуля (видно выше: "__main__" — файл запущен напрямую). В
# реальном проекте с несколькими файлами это сразу показывает, ИЗ
# КАКОГО модуля пришло сообщение, без ручного добавления префикса.
# Имена логгеров можно организовать иерархией через точку:
# "app.database", "app.api" — оба видны как потомки логгера "app".

db_logger = logging.getLogger("app.database")
api_logger = logging.getLogger("app.api")

db_logger.info("подключение к БД установлено")
api_logger.info("получен запрос GET /users")
# 12:34:56 [INFO] app.database: подключение к БД установлено
# 12:34:56 [INFO] app.api: получен запрос GET /users


# ════════════════════════════════════════════════════════════════════════
# 4. Свой формат и отдельный логгер (без дублирования через root)
# ════════════════════════════════════════════════════════════════════════
# basicConfig настраивает ROOT-логгер — сообщения "всплывают" туда от
# всех логгеров по умолчанию (propagation). Если добавить обработчик
# СВОЕМУ логгеру, а propagate оставить включённым — сообщение выведется
# ДВАЖДЫ (свой обработчик + root). `propagate = False` отключает это
# "всплытие" — логгер полностью независим от root и от его level'а.

custom_logger = logging.getLogger("payments")
custom_logger.setLevel(logging.DEBUG)  # свой уровень, ниже чем у root (INFO)
custom_logger.propagate = False  # не дублировать через root-обработчик

handler = logging.StreamHandler()
handler.setFormatter(
    logging.Formatter("[PAYMENTS] %(levelname)s: %(message)s")
)
custom_logger.addHandler(handler)

custom_logger.debug("списание 500.00 RUB со счёта #42")
# [PAYMENTS] DEBUG: списание 500.00 RUB со счёта #42
# (DEBUG показался ЗДЕСЬ, хотя у root-логгера уровень INFO — у этого
# логгера СВОЙ уровень и свой formatter, независимо от basicConfig)


# ════════════════════════════════════════════════════════════════════════
# 5. Логирование исключений: logger.exception() внутри except
# ════════════════════════════════════════════════════════════════════════
# logger.exception(msg) — это logger.error(msg) ПЛЮС автоматически
# прикреплённый traceback (эквивалент exc_info=True). Работает ТОЛЬКО
# внутри except-блока (там есть активное исключение для traceback).
# Заменяет print(f"Ошибка: {e}") — не теряя место и причину падения.

try:
    result = 10 / 0
except ZeroDivisionError:
    logger.exception("не удалось выполнить деление")
# 12:34:56 [ERROR] __main__: не удалось выполнить деление
# Traceback (most recent call last):
#   File "...", line ..., in <module>
#     result = 10 / 0
#              ~~~^~~
# ZeroDivisionError: division by zero


# ════════════════════════════════════════════════════════════════════════
# 6. handlers/formatters — обзорно
# ════════════════════════════════════════════════════════════════════════
# Handler — КУДА идут сообщения: StreamHandler (консоль, использован
# выше), FileHandler("app.log") (файл), RotatingFileHandler (файл с
# ограничением размера/ротацией), есть handlers и для внешних систем
# мониторинга. У одного логгера может быть НЕСКОЛЬКО handlers сразу
# (например, WARNING+ в файл, а всё подряд — в консоль при разработке).
# Formatter — КАК выглядит строка (какие поля: время, уровень, имя,
# сообщение — так же, как задан format= в basicConfig выше).
#
# В реальном проекте logging обычно настраивается ОДИН раз при старте
# приложения (конфиг), а во всём остальном коде — просто
# `logger = logging.getLogger(__name__)` и вызовы `.info()`/`.error()`.
